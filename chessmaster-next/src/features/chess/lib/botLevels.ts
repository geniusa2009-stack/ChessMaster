// Documented bot progression. "Bot Level" is an HONEST internal scale, NOT a calibrated Elo —
// we do not claim exact Elo without a reference population. Each level maps deterministically to
// engine parameters consumed by the existing engine (`levelFromElo`/negamax + optional Stockfish):
//   - skill:    Stockfish Skill Level 0..20 (when the SF worker is available)
//   - movetime: ms budget per move
//   - depth:    negamax fallback search depth
//   - blunder:  probability of a deliberate random (weak) move — drives perceived strength
//   - style:    move-selection bias (see persona docs)
// Strength increases monotonically with level (verified by tests): movetime/skill/depth up,
// blunder down. This is a real difference in play, not a renamed engine depth.
export type BotStyle = "balanced" | "aggressive" | "defensive" | "random";
export type BotTier = "Beginner" | "Developing" | "Intermediate" | "Advanced" | "Expert" | "Master";

export interface BotLevel {
  level: number;        // 1..24
  tier: BotTier;
  approxElo: number;    // indicative only (uncalibrated) — shown as guidance, not a claim
  skill: number;        // 0..20
  movetime: number;     // ms
  depth: number;        // negamax fallback
  blunder: number;      // 0..1
  style: BotStyle;
}

function tierFor(level: number): BotTier {
  if (level <= 4) return "Beginner";
  if (level <= 8) return "Developing";
  if (level <= 12) return "Intermediate";
  if (level <= 16) return "Advanced";
  if (level <= 20) return "Expert";
  return "Master";
}

// 24 levels generated by a documented monotonic formula (not hand-waved labels).
export const BOT_LEVELS: BotLevel[] = Array.from({ length: 24 }, (_, i) => {
  const level = i + 1;
  const t = i / 23; // 0..1
  return {
    level,
    tier: tierFor(level),
    approxElo: Math.round(400 + t * 2400),                 // 400 → 2800 indicative
    skill: Math.min(20, Math.round(t * 20)),
    movetime: Math.round(80 + t * 520),                    // 80 → 600 ms
    depth: level < 6 ? 1 : level < 14 ? 2 : 3,
    blunder: Math.max(0, +(0.35 - t * 0.35).toFixed(3)),   // 0.35 → 0.0
    style: "balanced",
  };
});

export function botLevel(level: number): BotLevel {
  const clamped = Math.min(BOT_LEVELS.length, Math.max(1, Math.floor(level)));
  return BOT_LEVELS[clamped - 1];
}

